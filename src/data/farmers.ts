export function getHighRiskFarmers(): Farmer[] {
  return SAMPLE_FARMERS.filter(f => {
    const daysUntilDue = Math.floor(
      (new Date(f.loanDueDate).getTime() - Date.now()) / (1000 * 60 * 60 * 24)
    );
    return daysUntilDue <= 45;
  });
}
